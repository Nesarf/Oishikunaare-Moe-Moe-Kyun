/**
 * Wiring facts: what each place needs written where, so the same rules land in a harness that is not
 * this one.
 *
 * This module is deliberately separate from the judging core, and it is the *only* one allowed to name
 * another program's files (a settings file, a `mcpServers` block, an `AGENTS.md`). `src/portable.mjs`,
 * `src/transcripts.mjs` and `bin/mmk.mjs` stay free of host names on purpose - `check:portable` enforces
 * that - so a reader can tell "the rules" from "the fifteen ways to install them" at a glance.
 *
 * Pure data and string building: no host import, no file read, no write. `mmk wire` prints these; a
 * person or an installer decides whether to apply them.
 *
 * @module oishikunaare-moe-moe-kyun/wire
 */

/**
 * Build the wiring table.
 * @param {object} input - `{ here, version, rules }`: the package root as a slash path, the version
 *   string, and the resolved rules text to embed in rules-file targets.
 * @returns {Record<string, { file: string, note: string, block: string }>} one entry per target.
 */
export function wireTargets({ here, version, rules }) {
  const hook = `node "${here}/adapters/claude-code.mjs"`;
  const rulesBlock = (target) => `<!-- generated by mmk wire ${target} (oishikunaare-moe-moe-kyun ${version}); edit the configuration, not this block -->\n## Moe house rules\n\n${rules}`;
  return {
    'claude-code': {
      file: '.claude/settings.json (project) or ~/.claude/settings.json (user)',
      note: 'Merge the hooks block. Stop corrects a breach while the turn is still open; the other two attach the rules. Verification status: documented contract plus recorded fixtures, not yet run against a live client.',
      block: JSON.stringify({
        hooks: {
          SessionStart: [{ hooks: [{ type: 'command', command: hook }] }],
          Stop: [{ hooks: [{ type: 'command', command: hook }] }],
          UserPromptSubmit: [{ hooks: [{ type: 'command', command: hook }] }],
        },
      }, null, 2),
    },
    mcp: {
      file: 'the MCP client configuration, under mcpServers',
      note: 'Any MCP client: mmk_rules, mmk_check and mmk_notice, plus the mmk://rules resource.',
      block: JSON.stringify({ mcpServers: { 'moe-house-rules': { command: 'node', args: [`${here}/adapters/mcp.mjs`] } } }, null, 2),
    },
    'agents-md': {
      file: 'AGENTS.md',
      note: 'Codex and anything else that reads AGENTS.md. Rules only - pair it with a hook to get corrections too.',
      block: rulesBlock('agents-md'),
    },
    'claude-md': {
      file: 'CLAUDE.md',
      note: 'Rules only; the claude-code target above adds the corrections.',
      block: rulesBlock('claude-md'),
    },
    'gemini-md': {
      file: 'GEMINI.md',
      note: 'Rules only.',
      block: rulesBlock('gemini-md'),
    },
    dsh: {
      file: 'profiles/<profile>/cordis.patch.yml',
      note: 'The plugin row, for a profile that does not install this package as a bundle (a bundle install needs no patch).',
      block: '- insert:\n    - id: oishikunaare-moe-moe-kyun\n      name: oishikunaare-moe-moe-kyun',
    },
  };
}
